-- month_summaries is rebuilt rather than altered: V1 declared unique(period)
-- inline, so its constraint name is database-generated and cannot be dropped
-- portably — and "one row per month" must become "one row per user per month".
alter table month_summaries rename to month_summaries_old;

create table month_summaries (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    period     varchar(7) not null,
    income     numeric(14,2) not null,
    saved      numeric(14,2) not null,
    eating_out numeric(14,2) not null,
    groceries  numeric(14,2) not null,
    transport  numeric(14,2) not null,
    other      numeric(14,2) not null,
    constraint fk_month_summaries_user foreign key (user_id) references users (id),
    constraint uq_month_summaries_user_period unique (user_id, period)
);

insert into month_summaries (user_id, period, income, saved, eating_out, groceries, transport, other)
select (select min(id) from users), period, income, saved, eating_out, groceries, transport, other
from month_summaries_old;

drop table month_summaries_old;
