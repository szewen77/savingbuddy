-- Multi-user: every row belongs to a user.
--
-- An existing single-user install is adopted, not abandoned: its data is
-- assigned to a user created from the current plan (email owner@localhost,
-- password "savingbuddy" — documented in the README with instructions to
-- change it). A fresh database gets no user here; registration creates one.

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null,
    password_hash varchar(100) not null,
    created_at    timestamp(6) not null,
    constraint uq_users_email unique (email)
);

